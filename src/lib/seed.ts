let n = 0;
function product(p: P): Product {
  n++;
  const slug = p.slug ?? p.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
  const inv = p.inventory ?? { model: "unique", quantity: 1, reserved: 0, state: "available", sku: `VB-${String(n).padStart(4, "0")}` };
  return {
    number: n,
    slug,
    occasions: [],
    dimensions: { lengthM: 5.5, widthM: 1.15, blousePieceM: 0.8 },
    weightG: 650,
    care: "Dry clean only. Store folded in muslin, refolding along new lines every few months. Keep zari away from perfume.",
    textileId: `t-${p.id.split("-")[1]}`,
    drape: DEFAULT_DRAPE,
    renders: [],
    tags: [],
    seo: { title: `${p.name} — ${p.weave} ${p.fabric} saree | VIBES`, description: p.description },
    status: "published",
    views: 0,
    createdAt: T0,
    updatedAt: T0,
    ...p,
    inventory: { ...inv, sku: inv.sku || `VB-${String(n).padStart(4, "0")}` },
  } as Product;
}

